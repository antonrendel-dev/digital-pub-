#!/usr/bin/env bash
# Правила проекта, которые нельзя нарушить молча.
#
# Зачем существует. 25.08.2026 выяснилось, что память проекта работает, а момент
# применения — нет: карточка project_ci_no_db с правилом «маршрут, читающий БД,
# либо динамический, либо со статическим запасом» была прочитана в начале сессии
# и нарушена через три часа. Память напоминает на старте, хук останавливает
# в момент записи файла.
#
# Сюда попадает только то, что проверяется по содержимому файла. Всё остальное
# (почему приняли решение, что уже отвергли) живёт в памяти проекта.

set -uo pipefail

INPUT=$(cat)
FILE=$(echo "$INPUT" | jq -r '.tool_input.file_path // ""')
[ -z "$FILE" ] && exit 0
[ ! -f "$FILE" ] && exit 0

case "$FILE" in
  */node_modules/*|*/.next/*|*/tests/*) exit 0 ;;
esac

WARN=""

# ── Правило 1. Маршрут, читающий БД, обязан быть динамическим ───────────────
# Повод: 23.08 пустые шарды sitemap, 25.08 карточки профессий с нулём вакансий.
# У раннера GitHub Actions нет доступа к базе, и статический пререндер уезжает
# на прод готовым пустым артефактом.
case "$FILE" in
  */app/*page.tsx|*/app/*route.ts|*/app/sitemap.ts)
    if grep -qE 'getPayload|getPostsBy|payload\.find' "$FILE" 2>/dev/null; then
      if ! grep -qE "^export const (revalidate|dynamic)" "$FILE" 2>/dev/null; then
        WARN="${WARN}
• Маршрут читает БД, но не объявляет revalidate или dynamic.
  Без этого он пререндерится на сборке, где базы нет, и уезжает на прод пустым.
  Так было 23.08 с шардами sitemap и 25.08 с карточками профессий.
  Память: project_ci_no_db"
      fi
    fi
    ;;
esac

# ── Правило 2. Многословный like дробится на слова ──────────────────────────
# Повод: 25.08 карточка рилсмейкера обещала 380 вакансий при 31 настоящей.
# Payload разбивает многословный запрос, «дизайнер презентаций» находит SMM-щика.
if grep -qE "like: *'[^']* [^']*'" "$FILE" 2>/dev/null; then
  WARN="${WARN}
• В запросе like стоит несколько слов — Payload ищет их по отдельности.
  «дизайнер презентаций» найдёт вакансию, где «дизайнер» в одном месте,
  а «презентаций» в другом. Нужен отсев по точной фразе после выборки.
  Пример: getPostsByProfession(queries, limit, phrases)"
fi

# ── Правило 3. Подстановка числа без защиты от нуля ─────────────────────────
# Повод: 25.08 в выдачу уехал title «Вакансии директолога — 0: Яндекс Директ».
if grep -qE "replace\( *'\{N\}'" "$FILE" 2>/dev/null; then
  WARN="${WARN}
• Число подставляется напрямую. При нуле в заголовок попадёт «— 0:»,
  а это в сниппете читается как «вакансий нет». Используйте fillCount()."
fi

# ── Правило 4. Новая посадочная — сначала проверить, кто уже ранжируется ────
# Повод: 26.08.2026 чуть не создали /professions/direktolog, не заметив, что
# по «яндекс директолог вакансии» уже показываются ДВЕ наши страницы —
# /tools/yandex-direct (позиция 16,3) и статья с июня (26,2). Третья сущность
# добавила бы каннибализации, а не трафика.
case "$FILE" in
  */lib/professions.ts|*/lib/keyword-map.ts)
    if git -C "$(dirname "$FILE")" diff --unified=0 -- "$FILE" 2>/dev/null | grep -qE "^\+.*(mainKeyword:|main: ')"; then
      WARN="${WARN}
• Добавлен новый целевой ключ. Перед созданием посадочной проверьте в GSC,
  кто уже по нему ранжируется:
    dimensions [query, page], фильтр query contains «<корень ключа>»
  Если наша страница уже есть — новая создаст каннибализацию, а не трафик.
  Так было с директологом 26.08: инструмент 16,3 и статья 26,2 уже делили запрос."
    fi
    ;;
esac

# Правило 5 (control-группа эксперимента переписки) снято на приёмке O11
# 05.09.2026: эксперимент свёрнут решением Тони 01.09, статьи разблокированы
# (память project_rewrite_experiment). Номер оставлен, чтобы ссылки не поехали.
ROOT=$(git -C "$(dirname "$FILE")" rev-parse --show-toplevel 2>/dev/null || echo "")

# ── Правило 6. Программные страницы «× город/регион» не создаём ─────────────
# Повод: аудит 04.09.2026 (O11): 1 100 тонких URL в индексе, решение «регион
# Россия» уже принято; геостраницы умножают тонкий индекс, а не трафик.
case "$FILE" in
  */app/*\[city\]*|*/app/*\[gorod\]*|*/app/*\[region\]*|*/app/*/city/*|*/app/*/gorod/*|*/app/*/goroda/*)
    WARN="${WARN}
• Это похоже на программную страницу «специализация × город/регион».
  Решение проекта: регион только Россия, геостраниц не делаем — они
  добавляют тонкие URL в индекс (1 100 уже там), а не трафик.
  Память: project_audit_2026_09_04_tasks (O11)"
    ;;
esac

# ── Правило 7. Новая статья — только под ключ из ядра ────────────────────────
# Повод: аудит 04.09.2026: 62 % статей без органического входа (Метрика
# 109131123, 90 дн., 54 из 86), 18 из 63 ордеров переписки отклонены как «чужой
# интент» (scripts/seo-audit/data/rewrite-orders.json). Ядро (O1) появится файлом
# scripts/content-factory/data/core-*.json; пока его нет — только напоминание.
# Это правило видит только правки агентов через Write/Edit: завод пишет файлы
# через fs и коммитит git-ом мимо хука, его покрывает шаг в .husky/pre-commit.
case "$FILE" in
  */content/articles/*.mdx)
    if [ -n "$ROOT" ] && ! git -C "$ROOT" ls-files --error-unmatch "$FILE" >/dev/null 2>&1; then
      CORE=$(ls "$ROOT"/scripts/content-factory/data/core-*.json 2>/dev/null | tail -1)
      if [ -n "$CORE" ]; then
        KEY=$(grep -oE '"keywords":"[^,"]+' "$FILE" | head -1 | sed 's/"keywords":"//')
        if [ -z "$KEY" ]; then
          WARN="${WARN}
• Новая статья без главного ключа в schemaJsonLd.keywords — не с чем сверить ядро $(basename "$CORE").
  Темы берутся только из ядра с пометкой «нужна страница» (O1/O11)."
        elif ! jq -e --arg k "$KEY" '.. | strings | select(test("^" + $k + "$"; "i"))' "$CORE" >/dev/null 2>&1; then
          WARN="${WARN}
• Новая статья под ключ «$KEY», которого нет в ядре $(basename "$CORE").
  Темы берутся только из ядра с пометкой «нужна страница» (O1/O11)."
        fi
      else
        echo "ℹ️  Новая статья: ядра scripts/content-factory/data/core-*.json пока нет (O1), проверка ключа пропущена." >&2
      fi
    fi
    ;;
esac

if [ -n "$WARN" ]; then
  echo "⚠️  Правила проекта — $(basename "$FILE"):${WARN}" >&2
  exit 2
fi

exit 0
