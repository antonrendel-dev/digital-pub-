import { hasServiceText, stripServiceTail } from '../../lib/strip-service-tail'

/**
 * Формулировки хвоста взяты из семи статей, где он реально нашёлся 01.09.2026.
 * Каждая — отдельный случай: агент писал отчёт по-своему, и первая ручная
 * чистка по одной формулировке пропустила две статьи.
 */
const BODY = '## Сколько платят\n\nВилка 40 000–150 000 ₽ в штате.\n'

const TAILS = [
  '\n---\n\n**Служебное, вне тела статьи — для приёмки seo:** вхождения «ключ» — ровно 6.',
  '\n---\n\nГотово для проверки агентом seo. Использованные скиллы: `dpub-content-standard`.',
  '\n---\n\nИспользованный скилл: `dpub-content-standard` (мастер-промпт v6.6).',
  '\n---\n\nИспользован скилл: `dpub-content-standard`. Готово для проверки агентом seo.',
  '\n---\n\nСкиллы: `dpub-content-standard` (мастер-промпт v6.6 — правила вхождений).',
  // 04.09.2026, дожим «софт скиллы»: хвост начался с метаданных, а «Скиллы:»
  // стояли третьей строкой — маркер искали только сразу за разделителем.
  '\n---\n\n**Title:** Софт скиллы: как проверить кандидата\n**Meta description:** Софт скиллы в digital: чеклист.\n\n**Скиллы:** `dpub-content-standard` — правила v6.6.',
]

describe('срез служебного хвоста при публикации', () => {
  it.each(TAILS)('срезает хвост: %s', (tail) => {
    // Сначала — что инвариант вообще срабатывает. Без этой строки половина
    // правки не покрыта: с регуляркой, не матчащей ничего, тест оставался
    // зелёным, и так P0 уехал в коммит (ревью 04.09.2026).
    expect(hasServiceText(BODY + tail)).toBe(true)
    const cleaned = stripServiceTail(BODY + tail)
    expect(hasServiceText(cleaned)).toBe(false)
    expect(cleaned).toContain('Вилка 40 000–150 000 ₽')
  })

  /**
   * Гейт писателя проверяет не тело, а весь MDX — хвост умеет заезжать
   * внутрь faqSchema, где начала строки перед ним нет. Значит маркеры
   * обязаны терпеть фронтматтер: поле `title:` есть у всех 85 статей.
   */
  const FRONTMATTER = [
    'title: "Резюме программиста: образец и что писать в 2026"',
    'metaTitle: "Резюме программиста: образец 2026"',
    'metaDescription: "Как собрать резюме программиста: структура, ошибки, шаблон."',
    'dateModified: "2026-09-04"',
  ].join('\n')

  it('не считает служебным фронтматтер обычной статьи', () => {
    expect(hasServiceText(`---\n${FRONTMATTER}\n---\n${BODY}`)).toBe(false)
  })

  it('ловит хвост, заехавший внутрь faqSchema одной строкой', () => {
    const line =
      `faqSchema: '[{"question":"Сколько платят?","answer":"Вилка 40 000 ₽. ` +
      'Скиллы: `dpub-content-standard` — правила v6.6."}]\''
    expect(hasServiceText(`---\n${FRONTMATTER}\n${line}\n---\n${BODY}`)).toBe(true)
  })

  it('не трогает статью без хвоста', () => {
    expect(stripServiceTail(BODY).trim()).toBe(BODY.trim())
  })

  it('не режет обычный горизонтальный разделитель в тексте', () => {
    const withRule = BODY + '\n---\n\n## Как войти в профессию\n\nЗа 1–3 месяца.\n'
    expect(stripServiceTail(withRule)).toContain('Как войти в профессию')
  })
})
