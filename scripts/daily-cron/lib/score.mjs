/**
 * Черновая оценка новой задачи.
 *
 * Крон не умеет читать смысл карточки, поэтому ставит осторожный балл по
 * признакам, которые видны из текста, и помечает его как черновой. Смысл не в
 * точности, а в том, чтобы задача вообще попала в очередь: без балла её никто
 * никогда не предложит.
 */

const RE = {
  demand: /(\d[\d\s]{2,})\s*(?:\/\s*мес|в месяц|показ)/i,
  ready: /(сделано|проверено|собрано|замер|готов|написан)/i,
  blocks: /(держит|блокирует|ждут|зависит от|после утверждения)/i,
  tony: /(регистрац|руками тони|\[тони\]|подтвержден|капч|оплат)/i,
}

export function draftScore(task) {
  const text = `${task.content || ''}\n${task.description || ''}`

  // Спрос: если в тексте есть частотность, берём её порядок, иначе середина.
  let s = 10
  const m = text.match(RE.demand)
  if (m) {
    const n = Number(m[1].replace(/\s/g, ''))
    s = n >= 10000 ? 25 : n >= 1000 ? 20 : n >= 300 ? 15 : 8
  }

  const g = RE.ready.test(text) ? 15 : 6
  const r = RE.blocks.test(text) ? 15 : 0
  const a = RE.tony.test(text) ? 3 : 12

  return { s, g, r, a, total: s + g + r + a }
}

export function draftScoreLine(task) {
  const { s, g, r, a, total } = draftScore(task)
  return [
    `БАЛЛ: ${total}/100  (спрос ${s}/30 · готовность ${g}/25 · разблокировка ${r}/25 · автономность ${a}/20)`,
    `Почему: черновая оценка крона по тексту карточки — уточнить руками`,
    '─'.repeat(40),
    '',
  ].join('\n')
}
