// Сборка промптов контент-завода. Вынесены из writer.ts отдельным модулем не ради
// красоты: writer.ts зовёт main() на верхнем уровне, импортировать его в jest нельзя,
// и промпт — самая объёмная часть завода — оставался без единого автотеста. Здесь
// чистые функции: на входе готовые данные, на выходе строка.
//
// Разделение труда после аудита 04.09.2026 (C4): всё, что касается покрытия и
// структуры, живёт в промпте планировщика и приезжает к писателю уже решённым —
// планом с типом каждого H2. Писателю остаются ТЗ, план и короткий свод правил:
// двадцать нумерованных пунктов стандарта модель читала до середины.

/** Тип H2-блока. Планировщик проставляет его каждому разделу, писатель по нему выбирает форму подачи. */
export type H2Type = 'definition' | 'salary' | 'howto' | 'comparison' | 'list' | 'story' | 'faq'

export const H2_TYPES: H2Type[] = [
  'definition',
  'salary',
  'howto',
  'comparison',
  'list',
  'story',
  'faq',
]

/** Типы блоков, где ответ обязан стоять в первом предложении: их читают из выдачи. */
export const ATOMIC_H2_TYPES: H2Type[] = ['definition', 'salary', 'howto']

/** Раздел плана. type и table приходят от планировщика; у старых планов их может не быть. */
export interface PlannedH2 {
  title: string
  type?: H2Type
  keyPoints: string[]
  factualAnchors?: string[]
  table?: boolean
}

export interface PlannerSeoData {
  intent: string
  lsi: string[]
  painPoints: string[]
  competitorH2s: string[]
  uniqueAngle: string
  dataGaps?: string[]
  mandatoryBigrams?: string[]
  antifakeMarkers?: string[]
}

export interface PlannerPromptInput {
  topic: { title: string; keyword: string; type: string }
  outlineHint: string
  seoData: PlannerSeoData
}

export interface WriterPromptInput {
  keyword: string
  tzText: string
  planText: string
  lsi: string[]
  dataGaps?: string[]
  successCriteria?: string[]
  voiceSample: string
  /** Динамические SEO-требования от аналитика. Пусто — блок не выводится. */
  dynamicSeoBlock: string
}

/** План в текст для промпта писателя: тип блока и признак таблицы видны сразу. */
export function renderPlanText(h2s: PlannedH2[]): string {
  return h2s
    .map((h, i) => {
      const type = h.type ? ` [${h.type}]` : ''
      const anchors = (h.factualAnchors || []).length
        ? `\n   Факты-якоря (обязательно включи): ${h.factualAnchors!.join('; ')}`
        : ''
      const table = h.table ? '\n   Таблица: да' : ''
      return `${i + 1}. ${h.title}${type}\n   Тезисы: ${h.keyPoints.join('; ')}${anchors}${table}`
    })
    .join('\n')
}

export function buildPlannerPrompt({ topic, outlineHint, seoData }: PlannerPromptInput): string {
  return `Ты контент-стратег. Составь детальный план статьи.

ТЕМА: ${topic.title}
КЛЮЧ: ${topic.keyword}
ТИП: ${topic.type}
${outlineHint ? `ОБЯЗАТЕЛЬНЫЙ ШАБЛОН ДЛЯ ЭТОГО ТИПА: ${outlineHint}` : ''}
ИНТЕНТ: ${seoData.intent}
LSI-слова: ${seoData.lsi.join(', ')}
Боли аудитории: ${seoData.painPoints.join('; ')}
Уникальный угол: ${seoData.uniqueAngle}
Чего не хватает для фактурного текста: ${(seoData.dataGaps || []).join('; ')}
${(seoData.mandatoryBigrams || []).length ? `ОБЯЗАТЕЛЬНЫЕ БИГРАММЫ В H2 (из реальных запросов Wordstat — вставить в заголовки H2 или первые предложения блоков): ${seoData.mandatoryBigrams!.join(', ')}` : ''}
${(seoData.antifakeMarkers || []).length ? `МИФЫ ДЛЯ ОПРОВЕРЖЕНИЯ (AIO-resistant контент — обязательно включи в тело статьи): ${seoData.antifakeMarkers!.join(' | ')}` : ''}

Ты отвечаешь за покрытие темы целиком: писатель получит только ТЗ и этот план и
структуру придумывать не будет. Чего нет в плане — того не будет в статье.

Требования к плану:
- 5-7 блоков H2
- ПЕРВЫЙ H2 — definition block: чёткое определение темы, что это такое (для AI-SEO и featured snippets)
- Каждый H2 раскрывает конкретную боль или вопрос аудитории
- ПРЕДПОСЛЕДНИЙ H2 — призыв смотреть вакансии на Диджитал Паб
- ПОСЛЕДНИЙ H2 — FAQ: 4-8 частых вопросов по теме (для featured snippets и AI-цитирования)
- Не дублируй структуру конкурентов: ${seoData.competitorH2s.join('; ')}

ЧЕК-ЛИСТ ПОКРЫТИЯ (проверь план по каждому пункту перед выдачей):
- FAN-OUT ОСИ (1.3): ≥6 принципиально разных аспектов темы в разных H2. Один H2 = один интент, два H2 с одним интентом запрещены. Для профессий оси: определение / зарплата / навыки / образование / карьерный рост / регионы / инструменты / форматы работы
- ENTITY ATTRIBUTE COVERAGE (3.12): для статей о профессии план ОБЯЗАН покрыть ≥9 из 11 атрибутов: 1) чем занимается специалист 2) когда нужен такой специалист 3) зарплата и стоимость обучения 4) конкретные числовые диапазоны с источником 5) сроки обучения и карьерный горизонт 6) форматы работы (офис/удалёнка, регионы) 7) каналы поиска работы (Диджитал Паб, hh.ru) 8) кому не подходит 9) алгоритм входа 10) пошаговое руководство 11) отличия от смежных профессий. Обязательны атрибуты 1, 4, 9
- ФУНКЦИИ H2 (9.8): покрытие ≥5 из 7 функций: DEFINITION / MECHANICS (как стать) / CONSTRAINTS (требования) / SEGMENTATION (для кого) / COMPARISON (vs альтернатива) / ACTUALITY (данные за текущий год) / DIAGNOSTICS (что делать если)
- ТИПЫ БЛОКОВ (9.1d): у каждого H2 проставь поле type из списка definition | salary | howto | comparison | list | story | faq. На статью — минимум 4 разных типа. Тип definition — только у первого блока, faq — только у последнего
- ФОРМУЛИРОВКИ (9.3a): 30-50 % заголовков H2 — вопросы читателя («Сколько зарабатывает X?», «Какие навыки нужны?»), остальные тематические утверждения. Сплошные вопросы читаются как FAQ-простыня
- ТАБЛИЦА (2.4): ровно одному H2 проставь table: true — тому, где есть что сравнивать по строкам и столбцам (зарплаты по уровням, инструменты по задачам). У остальных table: false
- ФАКТЫ-ЯКОРЯ: у каждого H2 — 2-3 конкретных факта или цифры, которые обязаны попасть в блок. Без выдумок: либо известный факт, либо формулировка «диапазон по данным крупных job-платформ»
- FAQ ИЗ ПОИСКА (1.4j): вопросы последнего H2 — из реальных запросов («как», «почему», «можно ли», «сколько»), не придуманные
- TITLE (4.1e): metaTitle — ключ в первых 20-30 символах (буквально), длина 55-65 симв., конкретная выгода или цифра рядом с ключом. Title ≠ H1 дословно

Выдай JSON (без лишнего текста):
{
  "h2s": [
    {
      "title": "Заголовок H2",
      "type": "definition",
      "keyPoints": ["тезис 1", "тезис 2"],
      "factualAnchors": ["конкретный факт или цифра, который обязан попасть в этот блок", "2"],
      "table": false
    }
  ],
  "metaTitle": "SEO заголовок строго до 60 символов с ключевым словом",
  "metaDesc": "SEO описание строго 130-155 символов, раскрывает пользу статьи",
  "slug": "url-slug-latinicej-bez-russkikh-bukv"
}`
}

export function buildWriterPrompt({
  keyword,
  tzText,
  planText,
  lsi,
  dataGaps,
  successCriteria,
  voiceSample,
  dynamicSeoBlock,
}: WriterPromptInput): string {
  const dataGapsBlock = (dataGaps || []).length
    ? `\nЧЕГО НЕ ХВАТАЕТ ДЛЯ ФАКТУРНОГО ТЕКСТА: ${dataGaps!.join('; ')} — не придумывай эти данные, пиши диапазон.`
    : ''
  const successBlock = (successCriteria || []).length
    ? `\nКРИТЕРИИ УСПЕХА: ${successCriteria!.join('; ')}`
    : ''
  const voiceBlock = voiceSample
    ? `\n\nОБРАЗЕЦ ГОЛОСА (подражай ритму и подаче, фразы не копируй):\n${voiceSample}`
    : ''
  const seoInsert = dynamicSeoBlock
    ? `\n\nДОПОЛНИТЕЛЬНЫЕ SEO-ТРЕБОВАНИЯ (от аналитика, приоритет высокий):\n${dynamicSeoBlock}`
    : ''

  return `Ты опытный SEO-копирайтер для российского рынка digital-вакансий.

Напиши статью для Диджитал Паб (d-pub.ru) — job board для digital-специалистов.

Ниже — согласованное ТЗ. По нему же статью будут принимать: каждый пункт с цифрой
проверяется механически, и статья с невыполненным пунктом не публикуется.

${tzText}

LSI-слова из поиска (вплети органично): ${lsi.join(', ')}${dataGapsBlock}${successBlock}

ПЛАН. Структура уже согласована — следуй ей и ничего не добавляй от себя. В скобках
у заголовка стоит тип блока, он задаёт форму подачи (правило 3):
${planText}

ПРАВИЛА НАПИСАНИЯ:

1. КРЮЧОК. Первые 2-3 предложения — не определение, а точка входа: число, факт или наблюдение, после которого хочется читать дальше. Крючок стоит сразу после H1, до первого H2, отдельным абзацем без подзаголовка. Определение темы дай внутри первого H2.
   Так надо: «В Telegram Ads не хватает людей. Специалисты зарабатывают на 20-40 % больше аналогов того же грейда во ВКонтакте.»
   Так не надо: «Таргетолог — специалист по настройке рекламы.» (определение) / «В этой статье мы разберём…» (анонс)

2. КЛЮЧ. Слова ключа "${keyword}" — в первых 60 словах, в первом H2 и в одном ответе FAQ, в любой падежной форме и порядке слов. Дословная форма — только в title и description. Всего по тексту не более 6 вхождений; дальше — синонимы и местоимения. Запрещено выделять ключ жирным и открывать статью конструкцией «${keyword} — это …»: приёмка отклонит и то, и другое.

3. ФОРМА БЛОКА ПО ТИПУ. Для типов definition, salary, howto первое предложение H2 — прямой самодостаточный ответ на вопрос блока (definition — определение, salary — число или диапазон, howto — «чтобы X, нужно…» либо шаг 1), а ключевые тезисы разбиты на абзацы по 40-60 слов: такой абзац AI цитирует целиком. Блоки типов comparison, list, story, faq пиши свободно — так, как удобно читать.

4. ФАКТЫ. Цифры по зарплатам и рынку — только с источником и датой в тексте («по данным hh.ru за <год>»). Точных данных нет — пиши диапазон «по данным крупных job-платформ — от N до M», не выдумывай суммы и количество вакансий. В первом абзаце явно укажи дату («на <текущий месяц и год>»). hh.ru, SuperJob и Росстат упоминай только текстом, без кликабельных ссылок — это конкуренты. 1-3 раза опровергни распространённый миф по теме с источником: своими словами, без формул «на самом деле» и «миф о том, что … неверен». Диджитал Паб упомяни 1-2 раза со ссылкой [Диджитал Паб](/vacancies), анкор — именно «Диджитал Паб», не «d-pub.ru».

5. ТАБЛИЦЫ. Таблиц не больше двух: обязательная — в том H2, где её пометил план; вторая допустима при объёме свыше 1500 слов. Таблица самодостаточна: понятна без текста вокруг. Графики её не заменяют.

6. FAQ. Последний H2: формат «### Вопрос?» → ответ 2-3 предложения, самодостаточный. Не более 8 вопросов, каждый закрывает кластер, не разобранный в теле статьи.

7. ГОЛОС И ЗАПРЕТЫ. Ритм неровный: длинные и короткие предложения чередуются по смыслу, а не по норме. Абзац из одного предложения — не чаще одного на статью и только как реальный вывод. После «например» — конкретное имя, число или ситуация. Позиция автора — там, где есть основание. Запрещены без исключений: вводные (однако, таким образом, следует отметить, стоит сказать); канцелярит (осуществляется, является, в рамках, в целях, на сегодняшний день); номинализации (осуществление → делать, проведение анализа → анализировать); метазачины («по запросу X пользователи ищут», «многие задаются вопросом»); оценки без доказательств (самый востребованный, огромный спрос, лучшие перспективы); переходы-роботы (подводя итог, в заключение, резюмируя, перейдём к, рассмотрим, как уже отмечалось, в данном разделе, не менее важно). Шаблоны «Мы разбираем тысячи вакансий» и «Миф о том, что … неверен» приёмка отклоняет.${voiceBlock}

Объём: 2000–2500 слов.
Markdown: ## для H2, ### для H3, **жирный** (для акцентов, никогда для ключа), таблицы, маркированные списки.${seoInsert}`
}
