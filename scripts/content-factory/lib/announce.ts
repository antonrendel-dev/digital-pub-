/**
 * Текст анонса статьи для публичного канала.
 *
 * Живёт отдельно от отправки, потому что уходит подписчикам: ошибку в формате
 * увидят все, а поправить её задним числом уже нельзя. Отдельный модуль без
 * скомпилированного двойника — единственный способ покрыть текст тестом:
 * собранный lib/telegram.js перебивает исходник при разрешении модулей.
 */

/** Куда уходит анонс. Рабочий чат — другое место и другой формат. */
export const ANNOUNCE_CHANNEL = '@web_vacancy'

/**
 * Две строки: приписка и ссылка под ней.
 *
 * Разметки нет намеренно — сообщение уходит без parse_mode, и любые теги
 * подписчики увидели бы буквально.
 */
export function announceText(url: string): string {
  return `Читайте новую статью на нашем сайте 👇🏻\n${url}`
}
