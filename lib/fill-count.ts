/**
 * Подстановка числа вакансий в title и description.
 *
 * Существует ради одного случая — когда число равно нулю. У раннера GitHub
 * Actions нет доступа к базе, поэтому любая страница, пререндеренная на сборке,
 * какое-то время отдаёт нули. 25.08.2026 это уехало на прод дважды: карточки
 * профессий с «сейчас нет открытых вакансий» при 142 живых и заголовок
 * «Вакансии директолога — 0: Яндекс Директ» в выдаче.
 *
 * Наивная подстановка тут не годится: «— 0:» в сниппете читается как
 * «вакансий нет», и человек не кликает. Ноль должен исчезать вместе
 * с разделителем, а не печататься.
 *
 * Правило простое: есть вакансии — подставляем число; нет — убираем
 * плейсхолдер вместе с прилегающим тире или двоеточием и восстанавливаем
 * заглавную букву, если срезали начало строки.
 */

const PLACEHOLDER = '{N}'

export function fillCount(template: string, count: number): string {
  if (!template.includes(PLACEHOLDER)) return template
  if (count > 0) return template.replace(PLACEHOLDER, String(count))

  const cleaned = template
    // «— {N}: SMM» → «: SMM», «— {N} вакансий» → «вакансий»
    .replace(/\s*[—–-]\s*\{N\}\s*:\s*/g, ': ')
    .replace(/\s*[—–-]\s*\{N\}\s*/g, ' ')
    // «{N} вакансий junior» → «вакансий junior» (в начале description)
    .replace(/\{N\}\s*/g, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([:,.])/g, '$1')
    .trim()

  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1)
}
