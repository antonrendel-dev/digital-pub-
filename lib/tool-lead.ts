/**
 * Лид под H1 на страницах инструментов.
 *
 * До 02.09.2026 там стояла одна и та же строка на всех восемнадцати страницах:
 * «Актуальные вакансии, где требуется {name} — собраны из Telegram-каналов
 * digital-рынка». Первые 60 слов страницы — место, где ищется ключ, и они были
 * семантически пусты, причём одинаково пусты на всех страницах сразу.
 *
 * Лид собирается из данных страницы, а не пишется руками по разу на инструмент:
 * ключ, число вакансий в выдаче и профессии, которые реально просят этот навык.
 * Так он уникален на каждой странице и не устаревает вместе с базой.
 *
 * Медианы в лиде нет намеренно. Карточка задачи предполагала брать
 * profession.salary.median, но на 02.09.2026 salary заполнен у двух профессий
 * из восьми, и ни одной из них нет на страницах инструментов. Писать вилку,
 * которой нет в данных, — ровно то, за что мы ругаем чужие сайты.
 */

/** Лид держим в один экран: первая карточка вакансии должна остаться видимой на 360×640. */
export const LEAD_MAX_CHARS = 450
export const LEAD_MAX_WORDS = 60

export interface LeadProfession {
  nameNominative: string
  count: number
}

/**
 * Строчная первая буква — но не у аббревиатур: сплошной toLowerCase превращал
 * «UX/UI-дизайнер» в «ux/ui-дизайнер» прямо в первых 60 словах страницы, то
 * есть портил и орфографию, и вхождение ключа (ревью 02.09.2026).
 */
function lowerFirst(name: string): string {
  return /^\p{Lu}\p{Lu}/u.test(name) ? name : name.charAt(0).toLowerCase() + name.slice(1)
}

export function buildToolLead(name: string, total: number, professions: LeadProfession[]): string {
  const plural =
    total % 10 === 1 && total % 100 !== 11
      ? 'вакансия'
      : [2, 3, 4].includes(total % 10) && ![12, 13, 14].includes(total % 100)
        ? 'вакансии'
        : 'вакансий'

  const head = total
    ? `Вакансии ${name} на d-pub.ru: ${total} ${plural} из Telegram-каналов digital-рынка, где ${name} стоит в требованиях.`
    : `Вакансии ${name} на d-pub.ru: собираем объявления из Telegram-каналов digital-рынка, где ${name} стоит в требованиях.`

  // Кого берут — это ответ на вопрос «а мне-то куда с этим навыком», и он
  // отличает страницу от соседних. Без данных о профессиях лид остаётся коротким.
  const top = professions.filter((p) => p.count > 0).slice(0, 2)
  if (!top.length) return head

  // Числа профессий в лид не идут намеренно. `total` — живой запрос к базе,
  // а count в lib/professions.ts — снимок, который обновляет отдельный
  // workflow. В одном предложении они разъезжаются до арифметически
  // невозможного: «3 вакансии … UX/UI-дизайнер — 15» (ревью 02.09.2026).
  const who = top.map((p) => lowerFirst(p.nameNominative)).join(' и ')
  const tail = ` Чаще всего навык просят там, где ищут ${who}.`
  const full = head + tail

  // Лид, вылезший за экран, отодвигает ленту вакансий — тогда лучше короткий.
  return full.length <= LEAD_MAX_CHARS && full.split(/\s+/).length <= LEAD_MAX_WORDS ? full : head
}
