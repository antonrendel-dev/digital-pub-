/**
 * Реестр «страница → её главный ключ».
 *
 * Заведён 25.08.2026 после замера, который показал цену отсутствия такого правила:
 * по кластеру «контент-менеджер + удалёнка» показываются четыре наши страницы,
 * 1 064 показа и ноль кликов. Страница с лучшей позицией (33–40) получает 7%
 * показов, а 77% забирает та, что стоит на 45–52 месте. Google видит четырёх
 * кандидатов и стабильно выбирает не лучшего.
 *
 * Правило простое: один главный ключ принадлежит ровно одной странице.
 * Тест tests/unit/keyword-map.test.ts падает, если ключ назначен дважды —
 * это делает повторение невозможным по построению, а не по договорённости.
 *
 * Карта наполняется по мере работы над страницами: сюда попадает то, что
 * замерено и осознанно назначено. Отсутствие страницы в карте не ошибка —
 * ошибка это две страницы на один ключ.
 *
 * Частотности — Вордстат, дата в комментарии рядом. Пересматривать при
 * следующем замере: спрос меняется, и «главный» ключ может перестать быть главным.
 */

export interface KeywordAssignment {
  /** Главный поисковый запрос страницы. Нормализуется при сравнении. */
  main: string
  /** Частотность Вордстата на дату замера. */
  volume?: number
  /** Почему именно этот ключ, если это неочевидно. */
  note?: string
}

/**
 * Приведение ключа к сравнимому виду.
 *
 * Что Вордстат НЕ различает (замер 25.08.2026, каждое утверждение — на парах,
 * совпавших до единицы). Всё перечисленное схлопывается, иначе две страницы
 * на одном ключе пройдут проверку как разные:
 *
 *  - ё и е: «ретушёр» и «ретушер» — по 5 496;
 *  - порядок слов: 7 пар из 7 совпали и в широком, и в точном соответствии.
 *    «рилсмейкер вакансии» = «вакансии рилсмейкера» — по 245 broad и 79 exact,
 *    «веб дизайнер вакансии» = «вакансии веб дизайнера» — по 412 exact;
 *  - дефис: «веб дизайнер вакансии» = «веб-дизайнер вакансии» — по 1 577;
 *  - форма слова: «веб аналитик вакансии» = «веб аналитика вакансии» — по 81.
 *
 * Что различает и потому НЕ нормализуется: разные корни («монтажер» 1 277 против
 * «видеомонтажер» 897), латиница против кириллицы («excel» 523 против «эксель» 419),
 * слитно против раздельно («рилсмейкер» 245 против «рилс мейкер» 56), опечатки
 * («ексель» 5, «риллсмейкер» 0).
 *
 * Первая редакция этого файла утверждала обратное про порядок слов, опираясь на
 * «вакансии рилсмейкера — 2». Двойка была из Вебмастера — это показы нашего сайта,
 * а не частотность запроса. Замер Вордстата даёт 245.
 */
/**
 * Отсечение падежного окончания.
 *
 * Нужно потому, что порядок слов схлопывается вместе со склонением:
 * «рилсмейкер вакансии» и «вакансии рилсмейкера» — один ключ (по 245),
 * но как строки различаются хвостом «-а». Полноценная лемматизация тут
 * избыточна: сравниваются короткие поисковые фразы, а не тексты.
 *
 * Слова короче пяти букв не трогаем — там окончание неотделимо от корня
 * («веб», «ии», «seo»), и обрезка склеила бы разные слова.
 */
const ENDINGS = [
  'иями',
  'ями',
  'ами',
  'ого',
  'ему',
  'ыми',
  'ими',
  'ая',
  'яя',
  'ое',
  'ее',
  'ые',
  'ие',
  'ой',
  'ей',
  'ый',
  'ий',
  'ом',
  'ем',
  'ах',
  'ях',
  'ов',
  'ев',
  'ую',
  'юю',
  'ам',
  'ям',
  'а',
  'я',
  'ы',
  'и',
  'у',
  'ю',
  'о',
  'е',
  'й',
]

function stem(word: string): string {
  if (word.length < 5) return word
  for (const end of ENDINGS) {
    if (word.length - end.length >= 4 && word.endsWith(end)) {
      return word.slice(0, -end.length)
    }
  }
  return word
}

export function normalizeKeyword(key: string): string {
  return key
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .map(stem)
    .sort()
    .join(' ')
}

