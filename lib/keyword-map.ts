/**
 * Страницы, делящие один нормализованный ключ.
 * Пустой массив — карта непротиворечива.
 */
export function findKeywordCollisions(
  map: Record<string, KeywordAssignment> = KEYWORD_MAP
): Array<{ key: string; urls: string[] }> {
  const byKey = new Map<string, string[]>()
  for (const [url, { main }] of Object.entries(map)) {
    const key = normalizeKeyword(main)
    byKey.set(key, [...(byKey.get(key) ?? []), url])
  }
  return [...byKey.entries()]
    .filter(([, urls]) => urls.length > 1)
    .map(([key, urls]) => ({ key, urls }))
}
