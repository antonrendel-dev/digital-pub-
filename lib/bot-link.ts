/**
 * Ссылки на бота с меткой источника.
 *
 * Раньше все ссылки вели на голый t.me/resume_vac_bot, и понять, с какой
 * страницы человек пришёл, было нельзя в принципе. Telegram отдаёт значение
 * параметра start первым аргументом команды — бот записывает его при первом
 * приходе, дальше оно живёт в его базе.
 *
 * Метка ограничена латиницей, цифрами и подчёркиванием: бот отбрасывает всё
 * остальное, и ссылка с кириллицей молча потеряла бы источник.
 */

const BOT = 'https://t.me/resume_vac_bot'

/** Откуда человек нажал — место в интерфейсе, а не адрес страницы. */
export type BotSource =
  | 'nav'
  | 'footer'
  | 'about'
  | 'legal'
  | 'vacancy_card'
  | 'vacancy_listing'
  | 'article'

/**
 * Ссылка на бота с меткой.
 *
 * Второй аргумент уточняет место внутри раздела — категорию листинга или слаг
 * статьи. Он приводится к тому же алфавиту, что ждёт бот: иначе метка вида
 * «smm/удалёнка» доехала бы обрезанной или не доехала совсем.
 */
export function botLink(source: BotSource, detail?: string): string {
  const suffix = detail
    ? '_' +
      detail
        .toLowerCase()
        .replace(/[^a-z0-9_-]+/g, '_')
        .replace(/-+/g, '_')
        .replace(/_+/g, '_')
        .replace(/^_|_$/g, '')
        .slice(0, 40)
    : ''
  return `${BOT}?start=${source}${suffix}`
}
