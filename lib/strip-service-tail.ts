/**
 * Срезает служебный хвост приёмки из текста статьи.
 *
 * Агент-писатель заканчивает работу отчётом для приёмки — «Готово для проверки
 * агентом seo», «Использованные скиллы: …», сводка вхождений ключей. Этот текст
 * не отделён от статьи ничем, кроме разделителя, и уезжал в опубликованный MDX
 * вместе с телом. 01.09.2026 такой хвост нашёлся в семи статьях, в том числе
 * внутри faqSchema — то есть в разметке FAQPage как текст ответа — и на самой
 * показываемой странице сайта его читали живые люди.
 *
 * Срезаем на публикации, а не ловим потом: тест ловит уже опубликованное,
 * а здесь текст не доходит до файла вовсе.
 */
export const SERVICE_TAIL =
  /\n\s*-{3,}\s*(?:(?:\*\*)?(?:Служебное|Скиллы:|Использован[а-яё]*\s+скилл|Готово для проверки|Мастер-промпт)|\*\*(?:Title|Meta description):)[\s\S]*$/i

/**
 * Те же маркеры без привязки к разделителю — для проверки, что чисто.
 *
 * Проверяется этим не только тело: писатель отдаёт сюда весь MDX вместе
 * с фронтматтером, потому что 01.09.2026 хвост нашёлся именно внутри
 * faqSchema. Отсюда два требования к маркерам.
 *
 * Первое: маркер обязан быть болдом. Первая версия правки 04.09.2026 ловила
 * `Title:` в любом виде — и матчила поле `title:` фронтматтера у всех 85
 * статей до единой, то есть публикация падала бы на каждой ночной статье.
 * Настоящий хвост писателя всегда приходит болдом, все шесть образцов
 * в тестах это подтверждают.
 *
 * Второе: «Скиллы:» с бэктиком ловится отдельно и без привязки к строке —
 * внутри faqSchema хвост склеивается с ответом FAQ в одну длинную строку,
 * и никакого начала строки перед ним нет.
 */
export const SERVICE_MARKER =
  /Готово для проверки|Использован[а-яё]*\s+скилл|Скиллы:\s*`|Служебное, вне тела|мастер-промпт v\d|^\s*\*\*(?:Title|Meta description):/im

export function stripServiceTail(markdown: string): string {
  return markdown.replace(SERVICE_TAIL, '\n').trimEnd() + '\n'
}

export function hasServiceText(text: string): boolean {
  return SERVICE_MARKER.test(text)
}
