/**
 * Срезает служебный хвост приёмки из текста статьи.
 *
 * Агент-писатель заканчивает работу отчётом для приёмки — «Готово для проверки
 * агентом seo», «Использованные скиллы: …», сводка вхождений ключей. Этот текст
 * не отделён от статьи ничем, кроме разделителя, и уезжал в опубликованный MDX
 * вместе с телом. 01.09.2026 такой хвост нашёлся в семи статьях, в том числе
 * внутри faqSchema — то есть в разметке FAQPage как текст ответа — и на самой
 * показываемой странице сайта его читали живые люди.
 *
 * Срезаем на публикации, а не ловим потом: тест ловит уже опубликованное,
 * а здесь текст не доходит до файла вовсе.
 */
export const SERVICE_TAIL =
  /\n\s*-{3,}\s*\n+\s*(?:\*\*)?(?:Служебное|Скиллы:|Использован[а-яё]*\s+скилл|Готово для проверки|Мастер-промпт|Title:|Meta description:)[\s\S]*$/i

/**
 * Те же маркеры без привязки к разделителю — для проверки, что чисто.
 *
 * `Title:`/`Meta description:` добавлены 04.09.2026: писатель отдал хвост,
 * начинающийся с них, а «Скиллы:» стояли третьей строкой — регулярка ждала
 * маркер сразу за разделителем и хвост пропустила. Он уехал и в тело, и в
 * faqSchema, где склеился с последним ответом FAQ. Здесь маркер привязан
 * к началу строки: в русском теле статьи строка «Title:» — служебная.
 */
export const SERVICE_MARKER =
  /Готово для проверки|Использован[а-яё]*\s+скилл|Служебное, вне тела|мастер-промпт v\d|^\s*\*{0,2}(?:Title|Meta description):/im

export function stripServiceTail(markdown: string): string {
  return markdown.replace(SERVICE_TAIL, '\n').trimEnd() + '\n'
}

export function hasServiceText(text: string): boolean {
  return SERVICE_MARKER.test(text)
}
