export const PROFESSION_SLUGS = Object.keys(PROFESSIONS)

/**
 * Обратная сторона моста: какие профессии просят этот инструмент.
 *
 * Одна и та же мысль, прочитанная с двух концов. На карточке профессии:
 * «видеомонтажёру нужен CapCut — просят в 30 вакансиях из 142». На странице
 * инструмента: «с CapCut берут видеомонтажёром». Пользователь, попавший на
 * любую из двух страниц, видит вторую половину и уходит по ней, а не в выдачу.
 *
 * Анкоры при этом асимметричны, и это не мелочь: со страницы инструмента вниз
 * уходит информационный сигнал («кем берут»), а с карточки профессии на листинг —
 * транзакционный («вакансии направления»). Если оба конца потянут один тип
 * запроса, страницы начнут конкурировать вместо того, чтобы усиливать друг друга.
 */
export function professionsByTool(
  toolSlug: string
): Array<{ profession: Profession; count: number }> {
  return Object.values(PROFESSIONS)
    .map((profession) => ({
      profession,
      count: profession.tools.find((t) => t.toolSlug === toolSlug)?.count ?? 0,
    }))
    .filter(({ count }) => count > 0)
    .sort((a, b) => b.count - a.count)
}
