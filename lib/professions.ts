/**
 * Карточки профессий для /professions.
 *
 * Чем это НЕ является: вторым листингом вакансий. Листинг по направлению живёт
 * в /vacancies/{направление} и отвечает на вопрос «где вакансии». Карточка
 * профессии отвечает на предыдущий вопрос — «кем меня возьмут и что для этого
 * нужно». Поэтому вакансий здесь показывается пять (PROFESSION_PREVIEW_LIMIT),
 * а не двадцать: больше — и страница превращается в конкурента листингу.
 *
 * Замер 25.08.2026, который определил состав раздела. Профессия попадает сюда,
 * только если сходятся ОБЕ стороны — спрос в Вордстате и наш собственный ресурс:
 *
 *   видеомонтажёр          897/мес   142 вакансии   берём
 *   веб-дизайнер         1 577/мес    20 вакансий   берём
 *   дизайнер презентаций   360/мес     2 вакансии   НЕ берём — см. ниже
 *   рилсмейкер             245/мес    42 вакансии   берём
 *   графический дизайнер 6 301/мес     1 вакансия   НЕ берём — soft-404
 *   веб-аналитик            81/мес    10 вакансий   НЕ берём — спроса нет,
 *                                                   и каннибализирует позицию 4
 *                                                   у /vacancies/analitika
 *
 * Дизайнер презентаций сначала прошёл отбор с 77 вакансиями и был отклонён при
 * повторном счёте. Разница в том, КАК считать: подстрока «презентац» находит 147
 * вакансий, но это «подготовить презентацию для клиента» у менеджеров и SMM.
 * Профильных, где презентации и есть работа, — две. Тот же механизм завышал
 * WordPress (19 против 2 настоящих) и Tilda.
 *
 * Графический дизайнер — самый жирный ключ замера и самая опасная ловушка:
 * поиск по всем 1 627 описаниям даёт ноль совпадений «графический дизайн».
 * Страница под 6 301 запрос с одной вакансией — это soft-404 под лучшим ключом.
 * Интент там информационный («сколько зарабатывает графический дизайнер» —
 * 29 показов в неделю по Вебмастеру), и закрывать его надо статьёй.
 *
 * ИНСТРУМЕНТЫ отбираются тремя условиями сразу, иначе блок врёт. Мало доли —
 * нужно ещё превышение над фоном по всей базе: показываем не то, что встречается
 * часто, а то, что встречается чаще обычного ИМЕННО ЗДЕСЬ. Порог 15% доли,
 * превышение ×1.8, минимум две вакансии.
 * Что это отсекло 25.08.2026: Figma у рилсмейкера (16,1% при фоне 9,2% — всего
 * ×1.7, то есть фон, а не признак профессии; дизайн у нас крупнейшая
 * специализация) и Photoshop у веб-дизайнера (8,7% — два упоминания, почти
 * наверняка копипаста из описаний 2018 года, когда сайты ещё рисовали в нём).
 * Нейросети отсекаются почти везде по той же причине: фон 21,6%.
 *
 * ВСЕ ЦИФРЫ НИЖЕ — ЗАМЕР, НЕ ОЦЕНКА. Зарплаты посчитаны по полю salary наших
 * же вакансий, частоты инструментов — по вхождениям в title и description.
 * Выдуманная вилка в разметке Occupation — прямой риск, поэтому там, где
 * выборка меньше 15 вакансий с указанной зарплатой, вилки нет вовсе.
 */

/**
 * Сколько вакансий показывает карточка профессии.
 *
 * Пять, а не двадцать: карточка — разбор профессии, а не листинг. При большем
 * числе она превращается во второй листинг и начинает конкурировать
 * с /vacancies/{направление} содержимым, а не только заголовком.
 *
 * Живёт здесь, а не рядом с запросом к базе: значение относится к профессиям,
 * и тестам нужно проверять его без импорта Payload.
 */
export const PROFESSION_PREVIEW_LIMIT = 5

export interface ProfessionTool {
  name: string
  /** В скольких вакансиях профессии инструмент назван. */
  count: number
  /** Ссылка на страницу инструмента, если она у нас есть. */
  toolSlug?: string
  /**
   * Чем считали count. Без этого поля цифру нельзя перепроверить: она
   * превращается в число, о происхождении которого известно только автору.
   * Строка, а не RegExp, — иначе объект нельзя сериализовать в снимок.
   */
  pattern: string
}

export interface ProfessionSalary {
  p25: number
  median: number
  p75: number
  /** Сколько вакансий с указанной зарплатой попало в расчёт. */
  sample: number
}

export interface Profession {
  slug: string
  name: string
  /** Именительный падеж для заголовков вида «Кем берут с CapCut». */
  nameNominative: string
  h1: string
  metaTitle: string
  metaDescription: string
  /** Главный ключ — он же запись в KEYWORD_MAP. */
  mainKeyword: string
  keywordVolume: number
  /** Широкая выборка из базы: Payload дробит многословный запрос на слова. */
  queries: string[]
  /** Точные фразы для отсева в памяти. Без них выборка ловит чужие вакансии. */
  phrases: string[]
  /** Сколько вакансий нашлось на дату замера. */
  vacanciesAtMeasure: number
  intro: string
  responsibilities: string[]
  salary: ProfessionSalary | null
  tools: ProfessionTool[]
  /** Куда уходит транзакционный сигнал — листинг направления. */
  relatedListing: { href: string; label: string }
  howToStart: string[]
  faq: Array<{ q: string; a: string }>
}

