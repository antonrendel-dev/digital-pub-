/**
 * Отсев постов канала, которые вакансией не являются.
 *
 * Повод: 25–27.08.2026 в канал @web_vacancy начали публиковать анонсы наших
 * же статей — «Читайте нашу статью 👇🏼» со ссылкой на d-pub.ru. Парсер завёл
 * на них три карточки вакансий (`chitayte-nashu-statyu_1740`, `_1766`,
 * `_1774`): сайт берёт вакансии из канала, канал получил ссылку на сайт,
 * круг замкнулся.
 *
 * Почему проверяем сырой HTML блока, а не разобранный текст. В посте ссылка
 * висит на якоре: `<a href="https://d-pub.ru/articles/…">"Заголовок"</a>`.
 * Парсер срезает теги раньше, чем успевает что-то проверить, и в тексте
 * остаётся только «Читайте нашу статью 👇🏼 "Заголовок"» — домена там уже нет.
 * Сырой блок ловит оба случая: и якорь, и превью ссылки, которое Telegram
 * рисует отдельным узлом за пределами текстового div.
 *
 * Проверено на живой выдаче t.me/s/web_vacancy 27.08.2026: из 20 постов
 * страницы правило зацепило ровно два анонса и ни одной настоящей вакансии.
 */

/**
 * Ссылка на наш собственный сайт.
 *
 * Границы по краям обязательны: без них правило зацепит гипотетический
 * `super-d-pub.ru.example` и выбросит живую вакансию. Дефис в d-pub входит
 * в имя домена, поэтому в класс границы он не попадает.
 */
const OWN_SITE = /(^|[^a-z0-9-])(?:www\.)?d-pub\.ru(?![a-z0-9-])/i

export interface SkipVerdict {
  skip: boolean
  /** Человекочитаемая причина — уходит в лог синка, чтобы отсев не был молчаливым. */
  reason?: string
}

/**
 * Нужно ли пропустить пост канала.
 *
 * @param rawBlockHtml сырой HTML блока сообщения со страницы t.me/s/,
 *                     до срезания тегов.
 */
export function shouldSkipPost(rawBlockHtml: string): SkipVerdict {
  if (OWN_SITE.test(rawBlockHtml)) {
    return { skip: true, reason: 'ссылка на d-pub.ru — это анонс нашей статьи, а не вакансия' }
  }
  return { skip: false }
}
