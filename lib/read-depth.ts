/**
 * Порог дочитывания статьи.
 *
 * Дочитыванием считается совпадение двух условий: человек добрался до конца
 * текста И провёл на странице правдоподобное для этого время. Каждое условие
 * по отдельности врёт — до низа долистывают мышью за две секунды, а открытая
 * и забытая вкладка набирает любое время без единого прочитанного слова.
 */

/** Знаков в минуту при беглом чтении русского текста средней сложности. */
export const CHARS_PER_MINUTE = 1200

/**
 * Какую долю статьи человек должен успеть прочесть, чтобы конец страницы
 * означал чтение, а не пролистывание. Треть — компромисс: по диагонали читают
 * быстрее полного времени, но за пять секунд не осиливают ничего.
 */
export const MIN_READ_SHARE = 1 / 3

/** Нижняя граница на случай совсем короткой заметки. */
export const MIN_SECONDS = 20

/** Сколько секунд нужно провести на статье такой длины, чтобы счесть её прочитанной. */
export function requiredSeconds(chars: number): number {
  const expected = (Math.max(0, chars) / CHARS_PER_MINUTE) * 60
  return Math.max(MIN_SECONDS, expected * MIN_READ_SHARE)
}

/** Долистал до конца и потратил на это достаточно времени. */
export function countsAsRead(chars: number, spentSeconds: number): boolean {
  return spentSeconds >= requiredSeconds(chars)
}
